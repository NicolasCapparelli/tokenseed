import type { GeneratedSystem } from "../engine";
import { flatten } from "../tokens";
import { cssVarName } from "./css";

/**
 * A Tailwind v4 theme that points at the CSS variables from toCss(), so utilities like
 * bg-surface-default, text-text-secondary, rounded-card and shadow-2 follow the active mode.
 */
export function toTailwind(system: GeneratedSystem, opts: { prefix?: string; cssFile?: string } = {}): string {
  const prefix = opts.prefix ?? "ts";
  const v = (path: string) => `var(${cssVarName(path, prefix)})`;
  const lines: string[] = [];
  const gradients: string[] = [];
  const paths = new Set([
    ...flatten(system.base).map(([p]) => p),
    ...system.modes.flatMap((m) => flatten(system.themes[m] ?? {}).map(([p]) => p)),
  ]);

  for (const p of paths) {
    const [head, ...rest] = p.split(".");
    const tail = rest.join("-");
    if (head === "color") lines.push(`--color-${tail}: ${v(p)};`);
    else if (head === "palette") lines.push(`--color-${tail}: ${v(p)};`);
    else if (head === "radius") lines.push(`--radius-${tail}: ${v(p)};`);
    else if (head === "shadow") lines.push(`--shadow-${tail}: ${v(p)};`);
    else if (head === "font" && rest[0] === "family") lines.push(`--font-${rest.slice(1).join("-")}: ${v(p)};`);
    else if (head === "motion" && rest[0] === "easing") lines.push(`--ease-${rest.slice(1).join("-")}: ${v(p)};`);
    else if (head === "blur") lines.push(`--blur-${tail}: ${v(p)};`);
    else if (head === "gradient") gradients.push(`@utility bg-gradient-${tail} {\n  background-image: ${v(p)};\n}`);
    else if (head === "breakpoint") lines.push(`--breakpoint-${tail}: ${v(p)};`);
    else if (head === "space" && rest.length === 2) lines.push(`--spacing-${tail}: ${v(p)};`);
    else if (head === "typography") {
      const n = `--text-${tail}`;
      const part = (suffix: string) => `var(${cssVarName(p, prefix)}-${suffix})`;
      lines.push(`${n}: ${part("font-size")};`);
      lines.push(`${n}--line-height: ${part("line-height")};`);
      lines.push(`${n}--letter-spacing: ${part("letter-spacing")};`);
      lines.push(`${n}--font-weight: ${part("font-weight")};`);
    }
  }

  return [
    `/* ${system.name}: Tailwind v4 theme generated by TokenSeed. Import after tailwindcss. */`,
    `@import "${opts.cssFile ?? "./tokens.css"}";`,
    "",
    "@theme inline {",
    ...lines.map((l) => `  ${l}`),
    "}",
    "",
    ...gradients.flatMap((g) => [g, ""]),
  ].join("\n");
}
