import { resolveValue, type GeneratedSystem } from "../engine";
import { presetById } from "../knobs/presets";
import { traitById } from "../knobs/traits";
import { flatten, type ColorValue, type ModeName, type Token } from "../tokens";
import { cssVarName } from "./css";
import { deepResolve } from "./dtcg";

const fmt = (metric: string, v: number) => (metric === "apca" ? `Lc ${v}` : `${v}:1`);
const row = (cells: string[]) => `| ${cells.map((c) => c.replace(/\|/g, "\\|")).join(" | ")} |`;
const table = (head: string[], rows: string[][]) =>
  [row(head), row(head.map(() => "---")), ...rows.map(row)].join("\n");

function literal(system: GeneratedSystem, token: Token, mode: ModeName): string {
  const v = deepResolve(system, token.$value, mode) as unknown;
  if (token.$type === "color") {
    const c = v as ColorValue;
    return c.alpha !== undefined && c.alpha !== 1 ? `${c.hex} @ ${c.alpha}` : c.hex;
  }
  if (token.$type === "dimension" || token.$type === "duration") {
    const d = v as { value: number; unit: string };
    return `${d.value}${d.unit}`;
  }
  if (token.$type === "typography") {
    const t = v as { fontFamily: string[]; fontSize: { value: number }; fontWeight: number; lineHeight: number };
    return `${t.fontFamily[0]} ${t.fontWeight}, ${t.fontSize.value}px / ${t.lineHeight}`;
  }
  return JSON.stringify(v);
}

/**
 * A single Markdown file an AI agent (or a person) can read to build UI in this system:
 * intent, rules, every semantic token with its value and purpose, and component recipes.
 */
export function toDesignMd(system: GeneratedSystem, opts: { prefix?: string } = {}): string {
  const prefix = opts.prefix ?? "ts";
  const { values } = system.resolved;
  const out: string[] = [];
  const [first] = system.modes;

  out.push(`# ${system.name} design system`, "");
  out.push(
    `Generated by TokenSeed (engine ${system.seed.engine}) for a ${String(values["identity.productType"])} product. ` +
      `Modes: ${system.modes.join(", ")}. Tokens follow the W3C DTCG 2025.10 format; CSS variables use the \`--${prefix}-\` prefix.`,
    "",
  );

  const presets = system.seed.presets.map((id) => presetById.get(id)).filter(Boolean);
  const traitLines = Object.entries(system.seed.traits).map(([id, t]) => {
    const trait = traitById.get(id);
    if (!trait) return "";
    const [lo, hi] = trait.label;
    const word = t < 0.35 ? lo : t > 0.65 ? hi : `balanced between ${lo.toLowerCase()} and ${hi.toLowerCase()}`;
    return `- **${word}**: ${trait.help}`;
  }).filter(Boolean);
  if (presets.length || traitLines.length) {
    out.push("## Personality", "");
    for (const p of presets) out.push(`- Style **${p!.label}**: ${p!.description}`);
    out.push(...traitLines, "");
  }

  out.push(
    "## Rules for building UI",
    "",
    "1. Use semantic tokens (`color.*`, `typography.*`, `space.inset|gap|section.*`, `radius.control|card|sheet|chip`, `shadow.*`). Never hard-code values.",
    "2. Never use `palette.*` directly in UI. Palettes exist so semantic roles can point at them.",
    "3. Pair every foreground with its intended background (`color.primary.on` on `color.primary.default`, `color.status.x.onSubtle` on `color.status.x.subtle`).",
    "4. Components use their `component.*` tokens when they exist.",
    "",
  );
  for (const kind of ["do", "dont", "note"] as const) {
    const items = system.guidelines.filter((g) => g.kind === kind);
    if (!items.length) continue;
    out.push(`### ${kind === "do" ? "Do" : kind === "dont" ? "Don't" : "Notes"}`, "");
    for (const g of items) out.push(`- (${g.topic}) ${g.text}`);
    out.push("");
  }

  const themed = (mode: ModeName) => flatten(system.themes[mode] ?? {});
  out.push("## Color roles", "");
  const colorRows = themed(first!).filter(([, t]) => t.$type === "color");
  out.push(
    table(
      ["Token", ...system.modes.map((m) => m[0]!.toUpperCase() + m.slice(1)), "Use"],
      colorRows.map(([p, t]) => [`\`${p}\``, ...system.modes.map((m) => literal(system, (flatten(system.themes[m]!).find(([q]) => q === p) ?? [p, t])[1], m)), t.$description ?? ""]),
    ),
    "",
  );

  const baseOf = (pred: (p: string, t: Token) => boolean) => flatten(system.base).filter(([p, t]) => pred(p, t));
  const section = (title: string, rows: [string, Token][]) => {
    if (!rows.length) return;
    out.push(`## ${title}`, "", table(["Token", "Value", "CSS variable", "Use"], rows.map(([p, t]) => [`\`${p}\``, literal(system, t, first!), `\`${cssVarName(p, prefix)}\``, t.$description ?? ""])), "");
  };
  section("Typography", baseOf((p) => p.startsWith("typography.") || p.startsWith("font.family")));
  section("Spacing", baseOf((p) => /^space\.(inset|gap|section)\./.test(p)));
  section("Sizing", baseOf((p) => p.startsWith("size.")));
  section("Radius", baseOf((p) => p.startsWith("radius.")));
  section("Motion", baseOf((p) => p.startsWith("motion.duration") || p.startsWith("transition.")));

  out.push("## Elevation", "");
  for (const [p, t] of themed(first!).filter(([, t]) => t.$type === "shadow")) out.push(`- \`${p}\`: ${t.$description ?? ""}`);
  out.push("");

  if (system.extras.length) {
    out.push("## Other values", "", "Values with no DTCG token type. They export as CSS custom properties.", "");
    out.push(table(["CSS variable", "Mode", "Value", "Use"], system.extras.map((e) => [`\`--${prefix}-${e.name}\``, e.mode ?? "all", `\`${e.value}\``, e.description ?? ""])), "");
  }
  const metaEntries = Object.entries(system.meta);
  if (metaEntries.length) {
    out.push("## Conventions", "");
    for (const [k, v] of metaEntries) out.push(`- ${k}: ${String(v)}`);
    out.push("");
  }

  out.push("## Components", "");
  for (const r of system.recipes) {
    out.push(`### ${r.name}`, "", r.description, "");
    out.push(`- Anatomy: ${r.anatomy.join(", ")}`, `- Variants: ${r.variants.join(", ")}`, `- States: ${r.states.join(", ")}`);
    const tokens = flatten(system.base).filter(([p]) => p.startsWith(`${r.tokens}.`));
    out.push(`- Tokens: ${tokens.map(([p, t]) => `\`${p}\` → ${typeof t.$value === "string" ? `\`${t.$value}\`` : literal(system, t, first!)}`).join("; ")}`);
    for (const rule of r.rules) out.push(`- Rule: ${rule}`);
    out.push("");
  }

  const failing = system.checks.filter((c) => !c.pass);
  out.push("## Accessibility checks", "");
  out.push(
    failing.length
      ? failing.map((c) => `- FAIL (${c.mode}): \`${c.foreground}\` on \`${c.background}\` is ${fmt(c.metric, c.value)}, needs ${fmt(c.metric, c.required)}`).join("\n")
      : `All ${system.checks.length} contrast checks pass (text target ${values["color.contrast"]}).`,
    "",
  );

  // Keep a pointer to the primary color so agents can sanity check what they render.
  const primary = resolveValue(system, "color.primary.default", first) as ColorValue | string;
  out.push(`_Primary color in ${first} mode: ${typeof primary === "string" ? primary : primary.hex}._`, "");
  return out.join("\n");
}
