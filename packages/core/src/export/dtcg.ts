import { resolveValue, type GeneratedSystem } from "../engine";
import { aliasPath, flatten, isAlias, setToken, type ModeName, type TokenTree } from "../tokens";

const json = (v: unknown) => JSON.stringify(v, null, 2) + "\n";

/** Replaces aliases (including ones nested in composite values) with literal values. */
export function deepResolve(system: GeneratedSystem, value: unknown, mode?: ModeName): unknown {
  if (isAlias(value)) return deepResolve(system, resolveValue(system, aliasPath(value), mode), mode);
  if (Array.isArray(value)) return value.map((v) => deepResolve(system, v, mode));
  if (value && typeof value === "object" && !("colorSpace" in value)) {
    return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, deepResolve(system, v, mode)]));
  }
  return value;
}

/** One tree per mode with every alias resolved: the easiest file for tools and agents to read. */
export function resolvedTree(system: GeneratedSystem, mode: ModeName): TokenTree {
  const out: TokenTree = {};
  const all = [...flatten(system.base), ...flatten(system.themes[mode] ?? {})];
  for (const [path, token] of all) {
    setToken(out, path, { $type: token.$type, $value: deepResolve(system, token.$value, mode), ...(token.$description ? { $description: token.$description } : {}) });
  }
  return out;
}

/** The system as a folder: DTCG token files, a DTCG resolver, the seed, and a manifest. */
export function toDtcgFiles(system: GeneratedSystem): Record<string, string> {
  const files: Record<string, string> = {
    "tokens/base.tokens.json": json(system.base),
    "seed.json": json(system.seed),
    "tokenseed.json": json({
      name: system.name,
      engine: system.seed.engine,
      modes: system.modes,
      recipes: system.recipes,
      guidelines: system.guidelines,
      checks: system.checks,
    }),
  };
  for (const mode of system.modes) {
    files[`tokens/${mode}.tokens.json`] = json(system.themes[mode]);
    files[`resolved/${mode}.tokens.json`] = json(resolvedTree(system, mode));
  }
  files["resolver.json"] = json({
    name: system.name,
    version: "2025-11-01",
    description: `${system.name}, generated by TokenSeed.`,
    sets: { base: { sources: [{ $ref: "tokens/base.tokens.json" }] } },
    modifiers: {
      theme: {
        description: "Color mode",
        contexts: Object.fromEntries(system.modes.map((m) => [m, [{ $ref: `tokens/${m}.tokens.json` }]])),
        default: system.modes[0],
      },
    },
    resolutionOrder: [{ $ref: "#/sets/base" }, { $ref: "#/modifiers/theme" }],
  });
  return files;
}
